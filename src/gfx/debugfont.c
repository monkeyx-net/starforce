static const char *const *glyph(char ch)
{
    ch = (char)toupper((unsigned char)ch);
    for (size_t i = 0; i < sizeof glyphs / sizeof glyphs[0]; i++)
        if (glyphs[i].ch == ch) return glyphs[i].rows;
    return NULL;
}

void debug_text(Framebuffer *fb, double x, double y, const char *text, uint32_t rgb)
{
    for (const char *p = text; *p; p++, x += DEBUG_ADVANCE) {
        if (*p == ' ') continue;
        const char *const *rows = glyph(*p);
        if (!rows) rows = glyph('?');
        for (int r = 0; r < DEBUG_GLYPH_H; r++)
            for (int c = 0; c < DEBUG_GLYPH_W; c++)
                if (rows[r][c] == '#') fill_rectf(fb, x + c, y + r, 1, 1, rgb);
    }
}

int debug_text_width(const char *text)
{
    int n = (int)strlen(text);
    return n ? n * DEBUG_ADVANCE - 1 : 0;
}
